#!/usr/bin/env python3
"""Regenerates Sources/CiceroCore/Rendering/UnicodeBlocks.swift, the Unicode block table the glyph grid
groups characters by, with the script each block is for: the one most of its characters are in, when they
outnumber those of every script (Common and Inherited) put together, so the Arabic block is Arabic, its comma
and vowel marks too, and General Punctuation is no script's. Also regenerates UnicodeScripts.swift, the script
of every character Unicode gives one other than Common and Inherited, like Han for 々 among CJK punctuation, and
the scripts Unicode lists a character for besides or instead of its own, like Bengali, Devanagari and more for the
danda, or Thaana for Arabic's digits.

Run by hand when a new Unicode version is out (Cicero itself never goes online):

    scripts/update-unicode-blocks.py               # downloads them for VERSION below
    scripts/update-unicode-blocks.py path/to/Blocks.txt path/to/Scripts.txt path/to/ScriptExtensions.txt path/to/PropertyValueAliases.txt
"""

import re
import sys
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/Blocks.txt"
SCRIPTS_URL = f"https://www.unicode.org/Public/{VERSION}/ucd/Scripts.txt"
EXTENSIONS_URL = f"https://www.unicode.org/Public/{VERSION}/ucd/ScriptExtensions.txt"
ALIASES_URL = f"https://www.unicode.org/Public/{VERSION}/ucd/PropertyValueAliases.txt"
OUT = Path(__file__).resolve().parent.parent / "Sources" / "CiceroCore" / "Rendering" / "UnicodeBlocks.swift"
SCRIPTS_OUT = OUT.with_name("UnicodeScripts.swift")


def read(argument, url):
    if argument:
        return Path(argument).read_text(encoding="utf-8")
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def scripts_by_code_point(text):
    found = {}
    for first, last, script in re.findall(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; (\w+)", text, re.M):
        for value in range(int(first, 16), int(last or first, 16) + 1):
            found[value] = script.replace("_", " ")
    return found


def block_script(first, last, scripts):
    counts = {}
    for value in range(first, last + 1):
        script = scripts.get(value)
        if script:
            counts[script] = counts.get(script, 0) + 1
    shared = counts.pop("Common", 0) + counts.pop("Inherited", 0)
    if not counts:
        return None
    script, count = max(counts.items(), key=lambda item: item[1])
    return script if count > shared else None


def main():
    text = read(sys.argv[1] if len(sys.argv) > 1 else None, URL)
    scripts_text = read(sys.argv[2] if len(sys.argv) > 2 else None, SCRIPTS_URL)
    extensions_text = read(sys.argv[3] if len(sys.argv) > 3 else None, EXTENSIONS_URL)
    aliases_text = read(sys.argv[4] if len(sys.argv) > 4 else None, ALIASES_URL)
    version = re.search(r"^# Blocks-(\S+)\.txt", text, re.M)
    blocks = re.findall(r"^([0-9A-F]+)\.\.([0-9A-F]+); (.+)$", text, re.M)
    if not version or not blocks:
        sys.exit("That doesn't look like Blocks.txt.")
    for name, other in (("Scripts", scripts_text), ("ScriptExtensions", extensions_text), ("PropertyValueAliases", aliases_text)):
        other_version = re.search(rf"^# {name}-(\S+)\.txt", other, re.M)
        if not other_version or other_version.group(1) != version.group(1):
            sys.exit(f"{name}.txt isn't from the same Unicode version as Blocks.txt.")
    scripts = scripts_by_code_point(scripts_text)

    lines = [
        f"// Generated by scripts/update-unicode-blocks.py from Unicode {version.group(1)} Blocks.txt and Scripts.txt; do not edit by hand.",
        "",
        "/// A named range of code points from the Unicode Character Database.",
        "struct UnicodeBlock: Sendable {",
        "    let range: ClosedRange<UInt32>",
        "    let name: String",
        "    /// The script the block is for, like Arabic for Arabic Presentation Forms-A; nil for one of signs every script",
        "    /// shares, like General Punctuation.",
        "    let script: String?",
        "",
        "    init(_ first: UInt32, _ last: UInt32, _ name: String, _ script: String? = nil) {",
        "        range = first...last",
        "        self.name = name",
        "        self.script = script",
        "    }",
        "",
        f'    static let unicodeVersion = "{version.group(1)}"',
        "",
        "    /// Every block, in code point order.",
        "    static let all: [UnicodeBlock] = [",
    ]
    for start, end, name in blocks:
        script = block_script(int(start, 16), int(end, 16), scripts)
        lines.append(f'        UnicodeBlock(0x{start}, 0x{end}, "{name.strip()}"' + (f', "{script}"' if script else "") + "),")
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(blocks)} blocks (Unicode {version.group(1)}) to {OUT.relative_to(OUT.parents[3])}")
    write_scripts(scripts, shared_scripts(extensions_text, aliases_text, scripts), version.group(1))


def shared_scripts(extensions_text, aliases_text, scripts):
    """The scripts each character is listed for besides or instead of its own, like Arabic and Syriac for the fathatan."""
    long_names = {short: long.replace("_", " ") for short, long in re.findall(r"^sc ; (\w+)\s*; (\w+)", aliases_text, re.M)}
    shared = {}
    for first, last, codes in re.findall(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*; ([\w ]+?)\s*#", extensions_text, re.M):
        for value in range(int(first, 16), int(last or first, 16) + 1):
            shared[value] = "|".join(long_names[code] for code in codes.split())
    return shared


def write_scripts(scripts, shared, version):
    ranges = []
    for value in sorted(scripts):
        script = scripts[value]
        if script in ("Common", "Inherited"):
            continue
        if ranges and ranges[-1][2] == script and ranges[-1][1] + 1 == value:
            ranges[-1][1] = value
        else:
            ranges.append([value, value, script])
    names = sorted({script for _, _, script in ranges})
    index = {name: number for number, name in enumerate(names)}
    lines = [
        f"// Generated by scripts/update-unicode-blocks.py from Unicode {version} Scripts.txt; do not edit by hand.",
        "",
        "/// The script of each character Unicode gives one, other than Common and Inherited, which every script shares.",
        "enum UnicodeScripts {",
        "    /// The script's name, like \"Arabic\"; nil for a character every script shares, or none.",
        "    static func script(of scalar: UInt32) -> String? {",
        "        var low = 0",
        "        var high = ranges.count / 3",
        "        while low < high {",
        "            let mid = (low + high) / 2",
        "            if ranges[mid * 3] <= scalar { low = mid + 1 } else { high = mid }",
        "        }",
        "        guard low > 0, scalar <= ranges[(low - 1) * 3 + 1] else { return nil }",
        "        return names[Int(ranges[(low - 1) * 3 + 2])]",
        "    }",
        "",
        "    /// The scripts Unicode lists a character for besides or instead of its own, like Arabic and Syriac for the",
        "    /// fathatan or Arabic, Thaana and Yezidi for Arabic's digits; nil for those it lists none for.",
        "    static func sharing(_ scalar: UInt32) -> [String]? {",
        "        var low = 0",
        "        var high = sharedRanges.count / 3",
        "        while low < high {",
        "            let mid = (low + high) / 2",
        "            if sharedRanges[mid * 3] <= scalar { low = mid + 1 } else { high = mid }",
        "        }",
        "        guard low > 0, scalar <= sharedRanges[(low - 1) * 3 + 1] else { return nil }",
        "        return sharedBy[Int(sharedRanges[(low - 1) * 3 + 2])].split(separator: \"|\").map(String.init)",
        "    }",
        "",
        "    static let names: [String] = [",
    ]
    lines += [f'        "{name}",' for name in names]
    lines += ["    ]", "", "    /// First, last and script, by its place in `names`, for each run of characters in one script, in code point order.",
              "    static let ranges: [UInt32] = ["]
    lines += [f"        0x{first:X}, 0x{last:X}, {index[script]}," for first, last, script in ranges]
    shared_ranges = []
    for value in sorted(shared):
        if shared_ranges and shared_ranges[-1][2] == shared[value] and shared_ranges[-1][1] + 1 == value:
            shared_ranges[-1][1] = value
        else:
            shared_ranges.append([value, value, shared[value]])
    sets = sorted({names for _, _, names in shared_ranges})
    set_index = {names: number for number, names in enumerate(sets)}
    lines += ["    ]", "", "    /// The scripts sharing characters, joined by |.", "    static let sharedBy: [String] = ["]
    lines += [f'        "{names}",' for names in sets]
    lines += ["    ]", "", "    /// First, last and scripts, by their place in `sharedBy`, for each run of characters they share, in code point order.",
              "    static let sharedRanges: [UInt32] = ["]
    lines += [f"        0x{first:X}, 0x{last:X}, {set_index[names]}," for first, last, names in shared_ranges]
    lines += ["    ]", "}", ""]
    SCRIPTS_OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(ranges)} script ranges ({len(names)} scripts) and {len(shared_ranges)} shared ones to "
          f"{SCRIPTS_OUT.relative_to(SCRIPTS_OUT.parents[3])}")


if __name__ == "__main__":
    main()
