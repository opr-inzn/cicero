#!/usr/bin/env python3
"""Regenerates Sources/PointCore/Rendering/UnicodeBlocks.swift, the Unicode block table the glyph grid
groups characters by.

Run by hand when a new Unicode version is out (Point itself never goes online):

    scripts/update-unicode-blocks.py                  # downloads Blocks.txt for VERSION below
    scripts/update-unicode-blocks.py path/to/Blocks.txt
"""

import re
import sys
import urllib.request
from pathlib import Path

VERSION = "15.1.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/Blocks.txt"
OUT = Path(__file__).resolve().parent.parent / "Sources" / "PointCore" / "Rendering" / "UnicodeBlocks.swift"


def main():
    if len(sys.argv) > 1:
        text = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        with urllib.request.urlopen(URL) as response:
            text = response.read().decode("utf-8")
    version = re.search(r"^# Blocks-(\S+)\.txt", text, re.M)
    blocks = re.findall(r"^([0-9A-F]+)\.\.([0-9A-F]+); (.+)$", text, re.M)
    if not version or not blocks:
        sys.exit("That doesn't look like Blocks.txt.")

    lines = [
        f"// Generated by scripts/update-unicode-blocks.py from Unicode {version.group(1)} Blocks.txt; do not edit by hand.",
        "",
        "/// A named range of code points from the Unicode Character Database.",
        "struct UnicodeBlock: Sendable {",
        "    let range: ClosedRange<UInt32>",
        "    let name: String",
        "",
        "    init(_ first: UInt32, _ last: UInt32, _ name: String) {",
        "        range = first...last",
        "        self.name = name",
        "    }",
        "",
        f'    static let unicodeVersion = "{version.group(1)}"',
        "",
        "    /// Every block, in code point order.",
        "    static let all: [UnicodeBlock] = [",
    ]
    for start, end, name in blocks:
        lines.append(f'        UnicodeBlock(0x{start}, 0x{end}, "{name.strip()}"),')
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(blocks)} blocks (Unicode {version.group(1)}) to {OUT.relative_to(OUT.parents[3])}")


if __name__ == "__main__":
    main()
