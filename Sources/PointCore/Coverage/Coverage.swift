// MARK: - Character sets

/// A list of characters a font should have, like Latin S or Adobe Latin 3.
public struct CharacterSetDefinition: Identifiable, Hashable, Sendable {
    public let id: String
    public let name: String
    public let summary: String
    public let groupID: String
    /// Position in its group; later sets in a series contain the earlier ones.
    public let level: Int
    /// Sorted, unique.
    public let scalars: [UInt32]

    public init(id: String, name: String, summary: String, groupID: String, level: Int, scalars: [UInt32]) {
        self.id = id
        self.name = name
        self.summary = summary
        self.groupID = groupID
        self.level = level
        self.scalars = scalars
    }

    public static let customGroupID = "custom"
    public var isCustom: Bool { groupID == Self.customGroupID }
}

public struct CharacterSetGroup: Identifiable, Sendable {
    public let id: String
    public let name: String
    public let credit: String
    public let url: String
    public let sets: [CharacterSetDefinition]
    /// Each set contains the previous one, so "the largest one a font has" makes sense (Latin S–XL, Adobe Latin).
    public let isSeries: Bool

    public init(id: String, name: String, credit: String, url: String, sets: [CharacterSetDefinition], isSeries: Bool) {
        self.id = id
        self.name = name
        self.credit = credit
        self.url = url
        self.sets = sets
        self.isSeries = isSeries
    }
}

