    /// Computes now if needed (for the Info panel and glyph grid of any face).
    public func coverage(computing face: FontFace) async -> FaceCoverage { fatalError("Implemented in PointCore") }

    public func clearCache() { fatalError("Implemented in PointCore") }
}

/// Families whose regular face has every character of some text, or misses at most a few.
public struct TextMatch: Identifiable, Sendable {
    public let family: Family
    public let missing: [UInt32]
    public var id: String { family.id }

    public init(family: Family, missing: [UInt32]) {
        self.family = family
        self.missing = missing
    }
}

