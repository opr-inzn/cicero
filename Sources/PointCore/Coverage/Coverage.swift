import Foundation

/// Unicode scalars a face covers, as sorted closed ranges.
public struct ScalarRanges: Sendable, Equatable {
    public init(_ ranges: [ClosedRange<UInt32>]) {
        fatalError("Implemented in PointCore")
    }

    public var count: Int { fatalError("Implemented in PointCore") }
    public func contains(_ scalar: UInt32) -> Bool { fatalError("Implemented in PointCore") }
    /// How many of these sorted, unique scalars are missing (one pass over both lists).
    public func missingCount(sorted scalars: [UInt32]) -> Int { fatalError("Implemented in PointCore") }
    public func missing(sorted scalars: [UInt32]) -> [UInt32] { fatalError("Implemented in PointCore") }
    /// Every covered scalar, in order.
    public var scalars: [UInt32] { fatalError("Implemented in PointCore") }
}

// MARK: - Languages

public enum LanguageSupport: Int, Comparable, Sendable {
    /// Every base character and required mark of an orthography.
    case base
    /// Base plus auxiliary characters.
    case full

    public static func < (a: Self, b: Self) -> Bool { a.rawValue < b.rawValue }
}

public struct Language: Identifiable, Hashable, Sendable {
    /// ISO 639-3, e.g. "deu".
    public let id: String
    public let name: String
    public let autonym: String?
    public let scripts: [String]
    public let speakers: Int
    /// false for historical languages.
    public let isCurrent: Bool
    /// The primary orthography's base characters, spaced, for display.
    public let sampleCharacters: String

    public init(id: String, name: String, autonym: String?, scripts: [String], speakers: Int, isCurrent: Bool, sampleCharacters: String) {
        self.id = id
        self.name = name
        self.autonym = autonym
        self.scripts = scripts
        self.speakers = speakers
        self.isCurrent = isCurrent
        self.sampleCharacters = sampleCharacters
    }
}

