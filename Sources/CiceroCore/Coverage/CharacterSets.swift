import Foundation

/// A list of characters a font should have, like Latin S or Adobe Latin 3.
public struct CharacterSetDefinition: Identifiable, Hashable, Sendable {
    public let id: String
    public let name: String
    public let summary: String
    public let groupID: String
    /// Position in its group; later sets in a series contain the earlier ones.
    public let level: Int
    /// Sorted, unique.
    public let scalars: [UInt32]

    public init(id: String, name: String, summary: String, groupID: String, level: Int, scalars: [UInt32]) {
        self.id = id
        self.name = name
        self.summary = summary
        self.groupID = groupID
        self.level = level
        self.scalars = scalars
    }

    public static let customGroupID = "custom"
    public var isCustom: Bool { groupID == Self.customGroupID }
}

public struct CharacterSetGroup: Identifiable, Sendable {
    public let id: String
    public let name: String
    public let credit: String
    public let url: String
    public let sets: [CharacterSetDefinition]
    /// The whole group is one series (Latin S–XL, Adobe Latin); see `CharacterSetSeries`.
    public let isSeries: Bool

    public init(id: String, name: String, credit: String, url: String, sets: [CharacterSetDefinition], isSeries: Bool) {
        self.id = id
        self.name = name
        self.credit = credit
        self.url = url
        self.sets = sets
        self.isSeries = isSeries
    }
}

/// Sets that each contain the one before, so "the largest one a font has" makes sense: Latin S–XL,
/// Adobe Latin, and Google's Latin, Cyrillic and Greek sets.
public struct CharacterSetSeries: Identifiable, Sendable {
    public let id: String
    public let name: String
    /// Smallest first.
    public let sets: [CharacterSetDefinition]
}

/// The built-in character sets (Resources/CharacterSets.json, generated by scripts/update-character-sets.py).
public final class CharacterSetCatalog: Sendable {
    public let groups: [CharacterSetGroup]
    /// Every built-in set, in group order.
    public let builtIn: [CharacterSetDefinition]
    /// Latin S–XL and Adobe Latin, then Google's by script.
    public let series: [CharacterSetSeries]

    public init(contentsOf url: URL?) {
        var file: File?
        if let url, let data = try? Data(contentsOf: url) {
            file = try? JSONDecoder().decode(File.self, from: data)
        }
        groups = (file?.groups ?? []).map { group in
            CharacterSetGroup(
                id: group.id, name: group.name, credit: group.credit, url: group.url,
                sets: group.sets.enumerated().map { level, set in
                    CharacterSetDefinition(id: set.id, name: set.name, summary: set.summary, groupID: group.id, level: level, scalars: Set(set.scalars).sorted())
                },
                isSeries: group.id == Self.latinSeriesID || group.id == Self.adobeSeriesID
            )
        }
        builtIn = groups.flatMap(\.sets)
        let sets = Dictionary(builtIn.map { ($0.id, $0) }) { first, _ in first }
        series = groups.filter(\.isSeries).map { CharacterSetSeries(id: $0.id, name: $0.name, sets: $0.sets) }
            + Self.googleSeries.compactMap { id, name, ids in
                let found = ids.compactMap { sets[$0] }
                return found.count == ids.count ? CharacterSetSeries(id: id, name: name, sets: found) : nil
            }
    }

    public static let latinSeriesID = "koeberlin"
    public static let adobeSeriesID = "adobe"

    /// Google's sets grow by script. GF Latin African isn't among them: it adds to Core, not to Plus.
    private static let googleSeries = [
        ("gf-latin", "GF Latin", ["gf-latin-kernel", "gf-latin-core", "gf-latin-plus"]),
        ("gf-cyrillic", "GF Cyrillic", ["gf-cyrillic-core", "gf-cyrillic-plus", "gf-cyrillic-pro"]),
        ("gf-greek", "GF Greek", ["gf-greek-core", "gf-greek-plus", "gf-greek-pro"]),
    ]

    public func definition(_ id: String) -> CharacterSetDefinition? {
        builtIn.first { $0.id == id }
    }

    /// A user's set as a definition.
    public static func definition(for custom: CustomCharacterSet, level: Int) -> CharacterSetDefinition {
        CharacterSetDefinition(
            id: custom.setID, name: custom.name, summary: "", groupID: CharacterSetDefinition.customGroupID,
            level: level, scalars: parse(custom.characters)
        )
    }

    /// Reads characters typed or pasted by hand: `U+00C1`, `0x00C1`, ranges like `U+0100–U+017F`
    /// or `U+0100-017F`, and plain characters. Whitespace and invisible characters are ignored.
    public static func parse(_ text: String) -> [UInt32] {
        let text = text.precomposedStringWithCanonicalMapping
        let code = /(?:U\+|0x)([0-9A-Fa-f]{1,6})(?:\s*[-–—]\s*(?:U\+|0x)?([0-9A-Fa-f]{1,6}))?/.ignoresCase()
        var found: Set<UInt32> = []
        var plain = ""
        var cursor = text.startIndex
        for match in text.matches(of: code) {
            plain += text[cursor..<match.range.lowerBound]
            cursor = match.range.upperBound
            guard var low = UInt32(match.1, radix: 16) else { continue }
            var high = match.2.flatMap { UInt32($0, radix: 16) } ?? low
            if high < low { swap(&low, &high) }
            high = min(high, low + 65535)
            for value in low...high {
                if let scalar = Unicode.Scalar(value), scalar.isCheckable { found.insert(value) }
            }
        }
        plain += text[cursor...]
        for scalar in plain.unicodeScalars where scalar.isCheckable {
            found.insert(scalar.value)
        }
        return found.sorted()
    }

    private struct File: Decodable {
        struct Group: Decodable {
            var id: String
            var name: String
            var credit: String
            var url: String
            var sets: [Entry]
        }

        struct Entry: Decodable {
            var id: String
            var name: String
            var summary: String
            var scalars: [UInt32]
        }

        var groups: [Group]
    }
}
